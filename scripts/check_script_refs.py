#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""管线脚本引用完整性检查 v2.1 (2026-10-15 重写):

v1 的教训: 目录常量正则只支持单段路径且不认 .resolve(), 把
`SCRIPT_DIR / "utils" / "x.py"`、`script_dir.parent / 'data_preprocessing_pipeline' / 'clean-data.py'`
这类**运行时完全正确**的引用全部误报为断链 (54 条里真断链≈0)。

v2.1 规则:
1. 目录常量: 支持 Path(__file__).resolve() 链、任意级 / "seg" 拼接、.parents[N] 索引;
   Path.home() 锚定的常量标记为仓库外, 引用直接跳过。
   ⚠ 基准是**文件本身**, .parent 链从文件起算 (v1/v2.0 从 py.parent 起算再叠一次,
   每个常量系统性多算一级 —— 54 条假警报的主要来源)。
2. 引用提取: 先剥离行注释与三引号字符串 (文档里的工具名不再误报),
   再匹配「路径链」 root / 'seg' / ... / 'x.py' 与裸相对引用。
3. 存在性判定: 常量链按解析目录判定; 裸相对引用依次试
   脚本目录 / 上一级 / 仓库根 / 各核心管线目录内 glob (跨管线调用不算断链)。
4. 同文件回退候选: 同一 basename 在本文件内有任一候选命中即不报
   (常见写法: 先试 A 再试 B, 只报 A 缺失是误报)。
5. ALLOWLIST: 运行时自生成脚本、外部 PATH 工具、第三方 vendored kit 内部
   引用、argv 标签, 显式列出理由, 不与真断链混在一起。
"""
import re
import sys
from pathlib import Path

R = Path(__file__).resolve().parent.parent
CORE_DIRS = ["virome_discovery_pipeline", "virome_analysis_pipeline",
             "public_metadata_pipeline", "virome_submission_pipeline",
             "virome_phylo_pipeline",
             # endogenous_virus_pipeline / host_expression_pipeline 已归档 (2026-10-11 → archive/)
             "biosoft"]

# 排除目录 (统一成 / 分隔再比较, 否则 Windows 反斜杠路径永远匹配不上)
EXCLUDE = ("/archive", "__pycache__", ".bak", "_backup", "_scratch", "_archive",
           "server_checks", "/build/", "/dist/", "node_modules")

# 运行时可解析的属性链 (parent/parents[N] 单独捕获)
_CALLS = r"(?:\.(?:resolve|absolute|strict|expanduser|as_posix)\(\))*"
_PARENS = r"(?:\.parent\b|\.parents\[\d+\])*"
_SEG = r"(?:\s*/\s*['\"][\w\-. +()]+['\"])"

# 目录常量: NAME = <锚点><calls><parent链><segs>
CONST_RE = re.compile(
    r"^([A-Za-z_][A-Za-z0-9_]*)\s*=\s*"
    r"(?:Path\(__file__\)" + _CALLS + r"(?P<parents>" + _PARENS + r")" +
    r"|(?:Path\.home\(\)(?:\.expanduser\(\))?" + _CALLS +
    r"|[A-Za-z_][A-Za-z0-9_]*)" + _CALLS + r"(?P<bparents>" + _PARENS + r"))" +
    r"(?P<segs>(?:" + _SEG + r")*)",
    re.M)

# 引用链: root<link> / 'seg' / ... / 'x.py'  (至少一段)
CHAIN_RE = re.compile(
    r"(?P<root>Path\(__file__\)" + _CALLS +
    r"|Path\.home\(\)" + _CALLS +
    r"|[A-Za-z_][A-Za-z0-9_]*)" +
    r"(?P<link>" + _PARENS + r")" +
    r"(?P<segs>(?:" + _SEG + r")+)")
_SEGEXTRACT = re.compile(r"['\"]([\w\-. +()]+)['\"]")

# 白名单: {文件名: 理由} — 引用目标不是 repo 内应存在的静态文件
ALLOWLIST = {
    # 运行时自生成 (gene_partition_dating.py 末尾 write_text 落盘到 run 目录)
    "parse_gene_beast.py": "runtime-generated by gene_partition_dating.py",
    "gcva_watch_parse.sh": "runtime-generated watch script (run-dir relative)",
    # 运行时写出的分析脚本 (snpeff_analysis.py: os.path.join(outdir, ...))
    "Execute_Figure_5_R_ComplexHeatmap.R": "runtime-generated by snpeff_analysis.py",
    # 外部 PATH 工具 (经 run_cmd 裸命令调用, 不在 repo)
    "SearchAccessionIdToTaxId.py": "external tool on PATH",
    "db_seqid2taxid_add_legth.py": "external tool on PATH",
    "make_ktaxonomy.py": "external tool on PATH",
    "rnaspades.py": "external SPAdes wrapper",
    "rnaviralspades.py": "external SPAdes wrapper",
    "bbduk.sh": "external BBTools",
    "bbmerge.sh": "external BBTools",
    "reformat.sh": "external BBTools",
    "ragtag.py": "external RagTag tool",
    # 按运行参数定位 (batch_virema_dvg.py: --virema-script 同目录)
    "DI-tector_06.py": "resolved via --virema-script arg parent",
    # 候选别名 (splitstree_native_viz.py: splitstree_unweight.py 优先, _unweight 为旧名)
    "_unweight.py": "legacy alias of splitstree_unweight.py",
    # 一次性补丁脚本, 目标已在 archive/
    "haplotype.py": "one-off patcher target (archived)",
    # 文档性复现命令 (dnasp.py 只把命令写进 reproducibility/commands.sh)
    "dnasp.py": "doc-only reproduction command string",
    # argv[0] 程序名标签 (phylo_pipeline.py:2468); 实际导入走 utils 包
    "splitstree_bridge.py": "sys.argv program label; import via utils package",
    # 第三方 vendored kit 内部引用 (biosoft/, 随上游发行版)
    "Get_migration_matrix_general_number_of_categories.py": "third-party VirPhyKit",
    "Insert_node_numbers.py": "third-party VirPhyKit",
    "function_subsample.py": "third-party VirPhyKit",
    "__init__.py": "third-party vfam_trees packaging",
    "run_phylobot.sh": "third-party YR-MPE",
    "vfam_viral_core.hmm": "third-party vfam_trees data file",
}


def strip_noise(text: str) -> str:
    """剥掉行注释与三引号字符串, 避免文档里的工具名被当成文件引用。"""
    text = re.sub(r'"""[\s\S]*?"""', ' "" ', text)
    text = re.sub(r"'''[\s\S]*?'''", " '' ", text)
    text = re.sub(r"#[^\n]*", "", text)
    return text


def _apply_parents(d: Path, link: str) -> Path:
    """按 .parent / .parents[N] 标记链下移目录。"""
    for tok in re.findall(r"\.parents\[\d+\]|\.parent\b", link):
        if tok.startswith(".parents"):
            n = int(re.search(r"\d+", tok).group())
            for _ in range(n + 1):          # pathlib .parents[0] == .parent
                d = d.parent
        else:
            d = d.parent
    return d


def dir_constants(py: Path, text: str) -> dict:
    """解析目录常量 → {常量名: Path 或 None(仓库外锚点)}。"""
    consts = {}
    pending = list(CONST_RE.finditer(text))
    for _ in range(len(pending) + 1):          # 反复解析, 处理常量间依赖
        progressed = False
        for m in pending:
            name = m.group(1)
            if name in consts:
                continue
            segs = _SEGEXTRACT.findall(m.group("segs") or "")
            if re.match(r"\w+\s*=\s*Path\.home\(\)", m.group(0)):
                consts[name] = None            # 仓库外锚点
                progressed = True
                continue
            if m.group("parents") is not None:  # Path(__file__) 锚点
                d = py                          # ⚠ 基准 = 文件本身 (v1 从 py.parent 起算, 双重下移)
            else:
                bm = re.match(r"\w+\s*=\s*([A-Za-z_][A-Za-z0-9_]*)", m.group(0))
                base = bm.group(1)
                if base not in consts:
                    continue
                if consts[base] is None:
                    consts[name] = None
                    progressed = True
                    continue
                d = consts[base]
            d = _apply_parents(d, m.group("parents") or m.group("bparents") or "")
            for s in segs:
                d = d / s
            consts[name] = d
            progressed = True
        if not progressed:
            break
    return consts


def in_repo(p: Path) -> bool:
    try:
        return str(p.resolve()).startswith(str(R))
    except OSError:
        return False


def find_in_core_dirs(ref: str):
    """跨管线调用回退: 在各核心管线目录下 glob 相对路径, 命中即视为有效引用。"""
    if not ref or Path(ref).is_absolute() or ref.startswith("~"):
        return None
    for d in CORE_DIRS:
        base = R / d
        if not base.exists():
            continue
        try:
            hits = [h for h in base.glob(ref) if h.is_file()]
            if hits:
                return hits[0]
            parts = Path(ref).parts
            if len(parts) > 1 and not any("<" in p or ">" in p for p in parts):
                hits = [h for h in base.rglob(ref) if h.is_file()]
                if hits:
                    return hits[0]
        except (NotImplementedError, ValueError, OSError):
            continue
    return None


missing, allowlisted, checked = [], [], 0
for d in CORE_DIRS:
    base = R / d
    if not base.exists():
        print(f"DIR MISSING: {d}")
        continue
    for py in sorted(base.rglob("*.py")):
        s = str(py)
        if any(x in s.replace("\\", "/") for x in EXCLUDE):
            continue
        try:
            raw = py.read_text(encoding="utf-8", errors="ignore")
        except Exception:
            continue
        text = strip_noise(raw)
        consts = dir_constants(py, raw)
        rel = s.replace(str(R) + "\\", "").replace(str(R) + "/", "")

        # ── 1) 路径链引用: 先收集, 再按「同 basename 有命中即放行」判定 ──
        chain_results = []                    # (segs, target 或 None=未知锚点/仓库外)
        for m in CHAIN_RE.finditer(text):
            root, link = m.group("root"), m.group("link")
            segs = _SEGEXTRACT.findall(m.group("segs"))
            if not segs:
                continue
            if root.startswith("Path.home()"):
                continue                      # 仓库外锚点, 不审
            if root == "Path(__file__)":
                cur = py
            elif root in consts:
                cur = consts[root]
                if cur is None:
                    continue
            else:
                chain_results.append((segs, None))   # 未知锚点, 目标未知
                continue
            target = _apply_parents(cur, link)
            for sg in segs:
                target = target / sg
            chain_results.append((segs, target))

        ok_bases = {Path(sg[-1]).name for sg, t in chain_results
                    if t is not None and t.exists()}
        for segs, target in chain_results:
            if target is None:
                continue                      # 未知锚点无法判定, 不误报
            fname = Path(segs[-1]).name
            if fname in ALLOWLIST:
                allowlisted.append((rel, "/".join(segs), ALLOWLIST[fname]))
                continue
            checked += 1
            if not target.exists():
                if fname in ok_bases:
                    continue                  # 同文件回退候选 (先试 A 再试 B)
                alt = find_in_core_dirs("/".join(segs))
                if alt is None:
                    missing.append((rel, "/".join(segs), target))

        # ── 2) 裸相对引用 (不在任何链里的 "*.py" 串) ──
        chain_spans = [m.span() for m in CHAIN_RE.finditer(text)]
        for m in re.finditer(r"""['"]([\w\-./\\]+\.(?:py|R|sh|jar))['"]""", text):
            if any(a <= m.start() < b for a, b in chain_spans):
                continue
            ref = m.group(1).replace("\\", "/")
            fname = Path(ref).name
            if fname in ALLOWLIST or fname in ok_bases:
                if fname in ALLOWLIST:
                    allowlisted.append((rel, ref, ALLOWLIST[fname]))
                continue
            if ref.startswith(("biosoft/", "virome_", "public_", "metadata_",
                               "submission_", "scripts/", "doc/")):
                checked += 1
                if not (R / ref).exists():
                    missing.append((rel, ref, R / ref))
                continue
            if "/" not in ref and not ref.endswith((".py", ".R", ".sh", ".jar")):
                continue
            checked += 1
            cands = [py.parent / ref, py.parent.parent / ref, R / ref]
            if not any(c.exists() for c in cands):
                alt = find_in_core_dirs(ref)
                if alt is None:
                    probe = (py.parent / ref).resolve()
                    if in_repo(probe):
                        missing.append((rel, ref, probe))

print(f"references checked: {checked}")
print(f"=== BROKEN REFERENCES ({len(missing)}) ===")
for src, ref, _t in sorted(set(missing)):
    print(f"  {src}  ->  {ref}")
print(f"=== ALLOWLISTED ({len(set(allowlisted))}) ===")
for src, ref, why in sorted(set(allowlisted)):
    print(f"  {src}  ->  {ref}  [{why}]")
